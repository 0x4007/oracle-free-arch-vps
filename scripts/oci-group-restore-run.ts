/**
 * Safe, injectable entry point for one isolated Oracle volume-group restore
 * drill. It reads only explicit private JSON inputs and never invents
 * acceptance evidence: acceptance and accepted-state cleanup require a
 * separate typed acceptance receipt supplied by the operator, and the create
 * stage stops at a durable CREATED result. The exceptions are the
 * receipt-free abort cleanups: an exact CREATED drill whose durable lifetime
 * already elapsed before acceptance, and an exact partial create journal that
 * reached one or more reconciled CREATED resources but never a durable result
 * because isolation proof or the clone launch failed. Every input path and
 * every persisted path must be a relative path rooted exactly at `.private`
 * without traversal segments, and only the journal and result are persisted
 * under that directory. The default invocation fails closed unless the exact
 * action and every required input are present.
 *
 * The OCI runner, its credentials and the cloud mutations stay in the
 * injected deps: this module holds no credentials and no production IDs.
 * The create action additionally binds a complete private Pi/helper
 * copied-volume preparation runtime configuration, and the production wrapper
 * wires the real preparation adapter into the pre-boot isolation gate only
 * when that full configuration validates against the reviewed plan; otherwise
 * create fails closed before any provider mutation.
 */
